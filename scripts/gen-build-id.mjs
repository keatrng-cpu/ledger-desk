#!/usr/bin/env node
/**
 * Stamp src/lib/build-id.ts from the ACTUAL commit being built.
 *
 * WHY THIS EXISTS
 * BUILD_ID was hand-edited. It read `093de49` while HEAD was `c445f19`, so the
 * badge whose entire job is proving "you are looking at the current build" was
 * itself stale — which makes a correctly-deployed app look cached and sends you
 * hunting a caching bug that is not there. A stamp a human has to remember to
 * update is not a stamp.
 *
 * Runs from `prebuild`, so every `npm run build` (including Vercel's) is
 * self-stamping. On Vercel the git dir may be absent, so VERCEL_GIT_COMMIT_SHA
 * is used first.
 */
import { execSync } from "node:child_process";
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "lib", "build-id.ts");

function sha() {
  // Vercel exposes the SHA even when .git is not shipped to the builder.
  const fromEnv =
    process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.GITHUB_SHA ?? "";
  if (fromEnv) return fromEnv.slice(0, 7);
  try {
    return execSync("git rev-parse --short HEAD", {
      cwd: root,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
  } catch {
    return "unknown";
  }
}

/** Keep whatever marker the app is currently branded with. */
function currentMarker() {
  try {
    const src = readFileSync(target, "utf8");
    const m = /BUILD_MARKER\s*=\s*"([^"]+)"/.exec(src);
    return m?.[1] ?? "desk";
  } catch {
    return "desk";
  }
}

const id = sha();
const marker = currentMarker();
const at = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");

writeFileSync(
  target,
  `/**
 * Build identity — GENERATED by scripts/gen-build-id.mjs on every build.
 * Do not hand-edit: a stamp you have to remember to update goes stale and then
 * lies about staleness. If the badge in the UI does not match the deployed
 * commit, the page is genuinely cached (see server/middleware/no-cache.ts).
 */
export const BUILD_ID = ${JSON.stringify(id)};
export const BUILD_LABEL = ${JSON.stringify(`desk-${id}-${marker}`)};
export const BUILD_AT = ${JSON.stringify(at)};
export const BUILD_MARKER = ${JSON.stringify(marker)};
`,
  "utf8",
);

console.log(`[build-id] ${id} (${marker}) @ ${at}`);
